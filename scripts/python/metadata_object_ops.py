def reviewed_dependency_map(snapshot, items):
    """Validate explicit hash reviews shared by object.remove and object.edit.remove."""
    from . import metadata as editor

    reviewed = {}
    for item in items:
        editor.require(isinstance(item, dict), "Invalid reviewed dependency")
        path = item.get("path")
        editor.relative(path)
        editor.require(path not in reviewed, "Duplicate reviewed dependency", 3)
        reason = item.get("reason")
        editor.require(isinstance(reason, str) and bool(reason.strip()), "Invalid reviewed dependency reason")
        data = snapshot.read("target", path, optional=True)
        editor.require(
            data is not None and editor.digest(data) == item.get("sha256"), "Stale reviewed dependency: " + path, 3
        )
        reviewed[path] = item
    return reviewed



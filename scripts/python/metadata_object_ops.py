def rename_metadata(
    snapshot,
    owner,
    path,
    original,
    child,
    new_name,
    target,
    reserved,
    *,
    structural_only=False,
    selected_forms=(),
    config=None,
    reviewed_dependencies=(),
):
    """Rename native metadata; the explicit route separates pending code review.

    Legacy edit/removal routes keep their strict dependency closure. Neither
    route infers absence of code dependencies from a missing textual match.
    """
    from . import metadata as editor
    from . import metadata_create as create

    old_name = editor.node_name(child)
    editor.require(isinstance(new_name, str) and editor.NAME.fullmatch(new_name), "Invalid new name")
    if new_name == old_name:
        return
    editor.require(new_name.casefold() != old_name.casefold(), "Case-only rename is not supported")
    editor.require(
        editor.prop(child, "ObjectBelonging") != "Adopted" and not editor.prop(child, "ExtendedConfigurationObject"),
        "Cannot rename an adopted child",
    )
    editor.require(new_name.casefold() not in {name.casefold() for name in reserved if name}, "Reserved new name")
    kind = etree.QName(child).localname
    owner_kind = etree.QName(owner).localname
    is_root = child is owner
    folder = path.removesuffix(".xml")
    destination = path.rsplit("/", 1)[0] + "/" + new_name if "/" in path else new_name
    if is_root:
        old_path, new_path = target, kind + "." + new_name
        editor.require(
            snapshot.read("target", destination + ".xml", optional=True) is None
            and snapshot.list_directory("target", destination, optional=True) is None,
            "Rename destination already exists",
            3,
        )
        if config is None:
            editor.require(
                kind == "CommonModule" and snapshot.package_entry(kind, old_name) is not None,
                "Configuration.xml required for this object type",
            )
            editor.require(snapshot.package_entry(kind, new_name) is None, "Rename destination is registered", 3)
        elif kind not in {"ExternalReport", "ExternalDataProcessor"}:
            editor.require(
                not borrow._linked(borrow._registrations(config), kind, new_name), "Rename destination is registered", 3
            )
    else:
        editor.require(
            not any(
                node is not child and (editor.prop(node, "Name") or node.text or "").casefold() == new_name.casefold()
                for node in child.getparent()
            ),
            "New name collides with an existing child",
            3,
        )
        collection = next(key for key, value in ADD_KINDS.items() if value == kind)
        # Use the same standard-name rules as creation, including Russian aliases.
        definition = {
            "type": {"ExternalReport": "Report", "ExternalDataProcessor": "DataProcessor"}.get(owner_kind, owner_kind),
            "name": editor.node_name(owner),
            "values" if collection == "enumValues" else collection: [{"name": new_name}],
        }
        parent_owner = child.getparent().getparent()
        if parent_owner.tag == f"{{{editor.MD}}}TabularSection":
            definition.pop(collection)
            definition["tabularSections"] = [
                {"name": editor.node_name(parent_owner), "attributes": [{"name": new_name}]}
            ]
        create.render_object(definition, editor.identity(owner), {})
        old_path, new_path = target + "." + kind + "." + old_name, target + "." + kind + "." + new_name
    documents, files = read_dependency_documents(
        snapshot,
        owner,
        path,
        pending_target=target if structural_only else None,
        reviewed_dependencies=reviewed_dependencies,
        rename_reference=old_path if structural_only else None,
    )
    if structural_only:
        rewrite_exchange_plan_contents(snapshot, files, {old_path: new_path})
    generated_names = {}
    generated_nodes = []
    if is_root or kind == "TabularSection":
        for generated in child.iter(f"{{{borrow.XR}}}GeneratedType"):
            old = generated.get("name", "")
            parts = old.split(".")
            position = 1 if is_root else 2
            editor.require(
                len(parts) > position
                and parts[position] == old_name
                and (is_root or parts[1] == editor.node_name(owner)),
                "Inconsistent generated type name",
            )
            parts[position] = new_name
            generated_names[old] = ".".join(parts)
            generated_nodes.append((generated, old))
    if selected_forms:
        from . import metadata_form_ops

        metadata_form_ops.rewrite_rename_references(snapshot, selected_forms, old_path, new_path, generated_names)
    child.find("m:Properties/m:Name", editor.NS).text = new_name
    for generated, old in generated_nodes:
        generated.set("name", generated_names[old])
    check_or_rewrite_references(
        snapshot, documents, owner, path, original, is_root, old_name, old_path, new_path, generated_names, new_name
    )
    if is_root:
        for source in files:
            if source == path or source.startswith(folder + "/"):
                renamed = destination + (".xml" if source == path else source[len(folder) :])
                editor.require(snapshot.read("target", renamed, optional=True) is None, "Rename file collision", 3)
                snapshot.stage(renamed, snapshot.read("target", source))
                snapshot.stage(source, None)
                if source in snapshot.pending_dependencies:
                    pending = snapshot.pending_dependencies.pop(source)
                    if config is None:
                        pending["targets"].discard(target)
                        pending["targets"].add(new_path)
                    snapshot.pending_dependencies[renamed] = pending
                if source in snapshot.rename_type_baselines:
                    snapshot.rename_type_baselines[renamed] = snapshot.rename_type_baselines.pop(source)
        if config is None:
            snapshot.rename_package_entry(kind, old_name, new_name)


def check_or_rewrite_references(
    snapshot,
    documents,
    owner,
    path,
    original,
    is_root,
    old_name,
    old_path,
    new_path,
    generated_names,
    new_name=None,
    removed_ids=(),
):
    """Rewrite only a rename; removal rejects every remaining reference."""
    from . import metadata as editor

    token = re.compile(r"(?<!\w)" + re.escape(old_name) + r"(?!\w)", re.IGNORECASE)
    for source, (root, data) in documents.items():
        before = editor.signature(root) if source != path else None
        for node in root.iter():
            if not isinstance(node.tag, str):
                continue
            parent = node.getparent()
            dumpinfo_name = (
                root.tag == f"{{{DUMPINFO}}}ConfigDumpInfo"
                and node.tag == f"{{{DUMPINFO}}}Metadata"
                and parent is not None
                and parent.tag == f"{{{DUMPINFO}}}ConfigVersions"
            )
            if dumpinfo_name:
                value = node.get("name", "")
                if value == old_path or value.startswith(old_path + "."):
                    editor.require(new_path is not None, "Cannot remove referenced metadata: " + source, 3)
                    node.set("name", new_path + value[len(old_path) :])
                editor.require(
                    not token.search(node.get("name", "")), "Unresolved rename attribute dependency: " + source
                )
            if removed_ids and node.tag in {
                f"{{{editor.MD}}}FillValue",
                f"{{{editor.MD}}}MinValue",
                f"{{{editor.MD}}}MaxValue",
            }:
                try:
                    referenced_id = str(uuid.UUID(node.text or ""))
                except ValueError:
                    referenced_id = None
                if referenced_id in removed_ids:
                    prefix, _, value_type = node.get(f"{{{XSI}}}type", "").partition(":")
                    editor.require(
                        node.nsmap.get(prefix) == editor.XS and value_type == "string",
                        "Cannot remove referenced UUID: " + source,
                        3,
                    )
            if removed_ids and node.tag in {
                f"{{{editor.V8}}}TypeId",
                f"{{{borrow.XR}}}TypeId",
                f"{{{editor.V8}}}ValueId",
                f"{{{borrow.XR}}}ValueId",
            }:
                try:
                    referenced_id = str(uuid.UUID(node.text or ""))
                except ValueError:
                    referenced_id = None
                if referenced_id in removed_ids:
                    raise editor.Rejected("Cannot remove referenced UUID: " + source, 3)
            # These fields are literal UI/documentation text, not executable paths.
            literal = node.tag == f"{{{editor.MD}}}Comment" or (
                node.tag == f"{{{editor.V8}}}content"
                and parent is not None
                and parent.getparent() is not None
                and etree.QName(parent.getparent()).localname
                in {
                    "Synonym",
                    "ToolTip",
                    "ObjectPresentation",
                    "ExtendedObjectPresentation",
                    "ListPresentation",
                    "ExtendedListPresentation",
                    "Explanation",
                }
            )
            literal |= (
                parent is not None
                and parent.tag == f"{{{editor.MD}}}Properties"
                and parent.getparent() is not None
                and (parent.getparent().tag, node.tag)
                in {
                    (f"{{{editor.MD}}}ScheduledJob", f"{{{editor.MD}}}Key"),
                    (f"{{{editor.MD}}}ScheduledJob", f"{{{editor.MD}}}Description"),
                    (f"{{{editor.MD}}}HTTPService", f"{{{editor.MD}}}RootURL"),
                }
            )
            declaration = (
                node.tag == f"{{{editor.MD}}}Name" and parent is not None and parent.tag == f"{{{editor.MD}}}Properties"
            )
            registration = (
                is_root
                and root.tag == f"{{{editor.MD}}}MetaDataObject"
                and len(root) > 0
                and root[0].tag == f"{{{editor.MD}}}Configuration"
                and parent is not None
                and parent.tag == f"{{{editor.MD}}}ChildObjects"
            )
            typed = bool(generated_names) and node.tag in {f"{{{editor.V8}}}Type", f"{{{editor.V8}}}TypeSet"}
            field = (
                node.tag == f"{{{borrow.XR}}}Field"
                and parent is not None
                and parent.tag in {f"{{{editor.MD}}}InputByString", f"{{{editor.MD}}}DataLockFields"}
            ) or (
                node.tag == f"{{{borrow.XR}}}DataPath"
                and parent is not None
                and parent.tag == f"{{{editor.MD}}}LinkByType"
            )
            reference = (
                node.tag == f"{{{borrow.XR}}}Item"
                and parent is not None
                and parent.tag
                in {
                    f"{{{editor.MD}}}References",
                    f"{{{editor.MD}}}BasedOn",
                    f"{{{editor.MD}}}Owners",
                    f"{{{editor.MD}}}RegisterRecords",
                    f"{{{editor.MD}}}RegisteredDocuments",
                    f"{{{editor.MD}}}Content",
                    f"{{{editor.MD}}}DefaultRoles",
                }
            )
            handler = (
                is_root
                and parent is not None
                and parent.tag == f"{{{editor.MD}}}Properties"
                and parent.getparent() is not None
                and (parent.getparent().tag, node.tag)
                in {
                    (f"{{{editor.MD}}}ScheduledJob", f"{{{editor.MD}}}MethodName"),
                    (f"{{{editor.MD}}}EventSubscription", f"{{{editor.MD}}}Handler"),
                }
                and bool(node.text)
            )
            form_reference = (
                parent is not None
                and parent.tag == f"{{{editor.MD}}}Properties"
                and etree.QName(node).namespace == editor.MD
                and etree.QName(node).localname
                in {
                    "DefaultObjectForm",
                    "DefaultFolderForm",
                    "DefaultListForm",
                    "DefaultChoiceForm",
                    "DefaultFolderChoiceForm",
                    "AuxiliaryObjectForm",
                    "AuxiliaryFolderForm",
                    "AuxiliaryListForm",
                    "AuxiliaryChoiceForm",
                    "AuxiliaryFolderChoiceForm",
                    "DefaultRecordForm",
                    "AuxiliaryRecordForm",
                    "DefaultForm",
                    "AuxiliaryForm",
                }
                and bool(node.text)
            )
            if registration:
                if node.tag == owner.tag and (node.text or "").casefold() == old_name.casefold():
                    editor.require(node.text == old_name, "Case-ambiguous registration")
                    node.text = new_name
            elif typed:
                prefix, colon, typename = (node.text or "").partition(":")
                if colon and node.nsmap.get(prefix) == borrow.CFG:
                    matches = [name for name in generated_names if name.casefold() == typename.casefold()]
                    if matches:
                        editor.require(typename in generated_names, "Case-ambiguous type reference")
                        editor.require(new_path is not None, "Cannot remove referenced metadata type: " + source, 3)
                        node.text = prefix + ":" + generated_names[typename]
                    else:
                        editor.require(not token.search(typename), "Unresolved metadata type reference: " + source)
                else:
                    editor.require(not token.search(node.text or ""), "Unresolved metadata type reference: " + source)
            elif field or reference or handler or form_reference:
                if reference:
                    prefix, _, typename = node.get(f"{{{XSI}}}type", "").partition(":")
                    editor.require(
                        typename == "MDObjectRef" and node.nsmap.get(prefix) == borrow.XR,
                        "Unsupported reference type: " + source,
                    )
                editor.require(
                    not len(node)
                    and isinstance(node.text, str)
                    and len(node.text.split(".")) >= 2
                    and all(editor.NAME.fullmatch(part) for part in node.text.split(".")),
                    "Invalid metadata reference: " + source,
                )
                if handler:
                    editor.require(
                        node.text.startswith("CommonModule.") and len(node.text.split(".")) == 3,
                        "Unsupported handler reference: " + source,
                    )
                if form_reference:
                    parts = node.text.split(".")
                    editor.require(
                        (len(parts) == 2 and parts[0] == "CommonForm")
                        or (len(parts) == 4 and parts[0] in FORM_REGISTRATION_OWNERS and parts[2] == "Form"),
                        "Unsupported form reference: " + source,
                    )
                if node.text.casefold() == old_path.casefold() or node.text.casefold().startswith(
                    old_path.casefold() + "."
                ):
                    editor.require(
                        node.text == old_path or node.text.startswith(old_path + "."),
                        "Case-ambiguous rename reference: " + source,
                    )
                    if new_path is None:
                        raise editor.Rejected("Cannot remove referenced metadata: " + source, 3)
                    node.text = new_path + node.text[len(old_path) :]
            elif not literal and not declaration:
                editor.require(not token.search(node.text or ""), "Unresolved rename dependency: " + source)
            editor.require(
                not any(
                    token.search(value) for key, value in node.attrib.items() if not (dumpinfo_name and key == "name")
                ),
                "Unresolved rename attribute dependency: " + source,
            )
        if new_path is not None and (source == path or editor.signature(root) != before):
            snapshot.stage(
                source,
                editor.serialize_like(
                    root, original if source == path else data, preserve_mixed_eol=new_path is not None
                ),
            )


def read_reference_list(owner, property_name):
    """Read the exact XML list used by both verification and editing."""
    from . import metadata as editor

    editor.require(property_name in {"Owners", "RegisterRecords", "BasedOn", "InputByString"}, "Unknown reference list")
    containers = owner.findall(f"{{{editor.MD}}}Properties/{{{editor.MD}}}{property_name}")
    editor.require(len(containers) == 1, "Missing or ambiguous reference list", 4)
    container = containers[0]
    editor.require(not container.attrib and not (container.text or "").strip(), "Invalid reference list structure", 4)
    field_list = property_name == "InputByString"
    tag = f"{{{borrow.XR}}}" + ("Field" if field_list else "Item")
    existing = []
    for child in container:
        editor.require(
            child.tag == tag and not len(child) and not (child.tail or "").strip(), "Invalid reference list item", 4
        )
        if field_list:
            editor.require(not child.attrib, "Invalid field attributes", 4)
        else:
            typed = child.get(f"{{{XSI}}}type", "").split(":")
            editor.require(
                set(child.attrib) == {f"{{{XSI}}}type"}
                and len(typed) == 2
                and typed[1] == "MDObjectRef"
                and child.nsmap.get(typed[0]) == borrow.XR,
                "Invalid metadata reference QName",
                4,
            )
        existing.append(child.text or "")
    editor.require(
        all(existing) and len({value.casefold() for value in existing}) == len(existing),
        "Empty or duplicate reference",
        4,
    )
    return container, existing


def edit_reference_list(snapshot, owner, property_name, action, values, base=None):
    """The legacy four list operations, resolved against the ordered snapshot."""
    from . import metadata as editor

    editor.require(action in {"add", "remove", "set"}, "Unknown reference list operation")
    containers = owner.findall(f"{{{editor.MD}}}Properties/{{{editor.MD}}}{property_name}")
    if not containers:
        # BasedOn заимствованного документа платформа отбрасывает при загрузке (R234, 2026-09-27).
        editor.require(
            property_name == "RegisterRecords"
            and action == "add"
            and etree.QName(owner).localname == "Document"
            and editor.prop(owner, "ObjectBelonging") == "Adopted"
            and base is not None
            and etree.QName(base).localname == "Document"
            and editor.prop(base, "ObjectBelonging") in {"", "Native"}
            and not editor.prop(base, "ExtendedConfigurationObject")
            and (editor.prop(owner, "ExtendedConfigurationObject") or "").lower() == editor.identity(base)
            and editor.node_name(owner) == editor.node_name(base),
            "Missing or ambiguous reference list",
            4,
        )
        assert base is not None
        base_containers = base.findall(f"{{{editor.MD}}}Properties/{{{editor.MD}}}{property_name}")
        editor.require(len(base_containers) <= 1, "Missing or ambiguous base reference list", 4)
        if base_containers:
            read_reference_list(base, property_name)
        existing = []
        container = etree.Element(f"{{{editor.MD}}}{property_name}")
        properties = owner.findall(f"{{{editor.MD}}}Properties")
        editor.require(len(properties) == 1, "Missing or ambiguous properties", 4)
        properties[0].append(container)
    else:
        container, existing = read_reference_list(owner, property_name)
    field_list = property_name == "InputByString"
    tag = f"{{{borrow.XR}}}" + ("Field" if field_list else "Item")
    editor.require(
        all(isinstance(value, str) and value for value in values)
        and len({value.casefold() for value in values}) == len(values),
        "Empty or duplicate reference",
    )
    known = {value.casefold(): value for value in existing}
    for value in values:
        editor.require(value.casefold() not in known or known[value.casefold()] == value, "Case-ambiguous reference", 3)
    owner_path = etree.QName(owner).localname + "." + editor.node_name(owner)
    for value in dict.fromkeys([*existing, *values]):
        parts = value.split(".")
        editor.require(all(editor.NAME.fullmatch(part) for part in parts), "Invalid reference path")
        if field_list:
            editor.require(
                len(parts) == 4
                and ".".join(parts[:2]) == owner_path
                and parts[2] in {"Attribute", "StandardAttribute"},
                "Invalid input field path",
            )
            candidates = [owner] + ([base] if base is not None else [])
            attribute = parts[2] == "Attribute"
            field_path = (
                "m:ChildObjects/m:Attribute"
                if attribute
                else f"{{{editor.MD}}}Properties/{{{editor.MD}}}StandardAttributes/{{{borrow.XR}}}StandardAttribute"
            )
            sources = []
            for candidate in candidates:
                matches = [
                    node
                    for node in candidate.findall(field_path, editor.NS)
                    if (editor.prop(node, "Name") if attribute else node.get("name", "")).casefold()
                    == parts[3].casefold()
                ]
                editor.require(
                    len(matches) <= 1
                    and all(
                        (editor.node_name(node) if attribute else node.get("name")) == parts[3] for node in matches
                    ),
                    "Unknown or ambiguous input attribute",
                    3,
                )
                sources.append(matches[0] if matches else None)
            editor.require(any(node is not None for node in sources), "Unknown input attribute", 3)
            if attribute and sources[0] is not None:
                local = sources[0]
                inherited = sources[1] if len(sources) > 1 else None
                if editor.prop(local, "ObjectBelonging") == "Adopted":
                    editor.require(
                        inherited is not None
                        and editor.prop(local, "ExtendedConfigurationObject").lower() == editor.identity(inherited),
                        "Invalid borrowed input attribute identity",
                        3,
                    )
                else:
                    editor.require(inherited is None, "Ambiguous native and base input attribute", 3)
            if not attribute:
                length_key = {"Code": "CodeLength", "Description": "DescriptionLength", "Number": "NumberLength"}.get(
                    parts[3]
                )
                if length_key:
                    length = editor.prop(owner, length_key) or (
                        editor.prop(base, length_key) if base is not None else ""
                    )
                    editor.require(length.isdecimal(), "Invalid standard input attribute length")
        else:
            editor.require(len(parts) == 2, "Expected object reference")
            if property_name == "Owners":
                editor.require(parts[0] == "Catalog", "Owner must be a Catalog")
            elif property_name == "RegisterRecords":
                editor.require(parts[0] in REGISTER_KINDS, "Expected register reference")
            read_object(snapshot, value)
    result = (
        existing + [value for value in values if value not in existing]
        if action == "add"
        else [value for value in existing if value not in values]
        if action == "remove"
        else list(values)
    )
    if field_list:
        for value in result:
            parts = value.split(".")
            if parts[2] == "StandardAttribute":
                length_key = {"Code": "CodeLength", "Description": "DescriptionLength", "Number": "NumberLength"}.get(
                    parts[3]
                )
                if length_key:
                    length = editor.prop(owner, length_key) or (
                        editor.prop(base, length_key) if base is not None else ""
                    )
                    editor.require(length.isdecimal() and int(length) > 0, "Disabled standard input attribute")
    if result == existing:
        return
    container[:] = []
    container.text = None
    for value in result:
        child = etree.SubElement(container, tag, nsmap={"xr": borrow.XR})
        if not field_list:
            child.set(f"{{{XSI}}}type", "xr:MDObjectRef")
        child.text = value


def edit_object(snapshot, operation):
    from . import metadata as editor
    from . import metadata_create as create

    definition = operation["parameters"]["definition"]
    reviewed_dependencies = reviewed_dependency_map(snapshot, operation["parameters"].get("reviewedDependencies", ()))
    additions = definition.get("add", {})
    modifications = definition.get("modify", {})
    removals = definition.get("remove", {})
    content_renames = definition.get("contentRenames", {})
    content_deduplicate = definition.get("contentDeduplicate", False)
    exchange_plan_content = definition.get("exchangePlanContent")
    editor.require(
        bool(definition)
        and set(definition)
        <= {"add", "modify", "remove", "_complex", "contentRenames", "contentDeduplicate", "exchangePlanContent"}
        and ("_complex" not in definition or bool(definition["_complex"]))
        and ("contentRenames" not in definition or bool(content_renames))
        and ("contentDeduplicate" not in definition or content_deduplicate is True)
        and ("remove" not in definition or removals and all(removals.values()))
        and set(removals) <= {*ADD_KINDS, *REGISTRATION_OWNERS}
        and ("add" not in definition or additions and all(additions.values()))
        and set(additions) <= {*ADD_KINDS, *REGISTRATION_OWNERS}
        and (
            "modify" not in definition
            or modifications
            and all(modifications.values())
            and set(modifications) <= {*ADD_KINDS, "properties"}
        )
        and all(
            bool(value) and all(bool(value[action]) for action in ("add", "modify", "remove") if action in value)
            for value in modifications.get("tabularSections", {}).values()
        ),
        "Object edit operation is not connected",
    )
    config, owner, path, original = read_object(snapshot, operation["target"])
    before_signature = editor.signature(owner)
    owner_kind: str = operation["target"].split(".")[0]
    if content_renames or content_deduplicate:
        editor.require(
            owner_kind == "ExchangePlan", "contentRenames and contentDeduplicate are only supported for ExchangePlan"
        )
        if content_renames:
            validate_exchange_plan_content_renames(snapshot, owner_kind, content_renames)
        content_path = path.removesuffix(".xml") + "/Ext/Content.xml"
        content_data = snapshot.read("target", content_path)
        rewrite_exchange_plan_contents(
            snapshot,
            {content_path: content_data},
            content_renames,
            require_reference=bool(content_renames),
            deduplicate=content_deduplicate,
        )
    editor.require(
        exchange_plan_content is None or owner_kind == "ExchangePlan",
        "ExchangePlan content edit requires an ExchangePlan target",
    )
    editor.require(
        all(
            owner_kind in (REGISTRATION_OWNERS[key] if key in REGISTRATION_OWNERS else ADD_OWNERS[key])
            for key in additions
        )
        and all(
            owner_kind in (REGISTRATION_OWNERS[key] if key in REGISTRATION_OWNERS else ADD_OWNERS[key])
            for key in removals
        )
        and all(key == "properties" or owner_kind in ADD_OWNERS[key] for key in modifications),
        "Child kind is not allowed for this owner",
    )
    children = owner.find(f"{{{editor.MD}}}ChildObjects")
    if children is None and additions:
        children = etree.SubElement(owner, f"{{{editor.MD}}}ChildObjects")
    reserved = set()
    reserved.update(
        node.get("name")
        for node in owner.findall(
            f"{{{editor.MD}}}Properties/{{{editor.MD}}}StandardAttributes/{{{borrow.XR}}}StandardAttribute"
        )
    )
    base = exact_base_owner(snapshot, owner, path)
    if base is not None:
        reserved.update(
            editor.prop(node, "Name") or node.text for node in base.findall(f"{{{editor.MD}}}ChildObjects/*")
        )
        reserved.update(
            node.get("name")
            for node in base.findall(
                f"{{{editor.MD}}}Properties/{{{editor.MD}}}StandardAttributes/{{{borrow.XR}}}StandardAttribute"
            )
        )

    def add(collection, attribute, container, parent_path, reserved_names, section_name=None):
        kind = ADD_KINDS[collection]
        name = attribute["name"]
        editor.require(
            editor.NAME.fullmatch(name)
            and name.casefold() not in {value.casefold() for value in reserved_names if value},
            "Invalid or reserved attribute name",
        )
        existing = [
            node for node in container if (editor.prop(node, "Name") or node.text or "").casefold() == name.casefold()
        ]
        editor.require(len(existing) <= 1, "Ambiguous existing attribute", 3)
        editor.require(not existing or existing[0].tag == f"{{{editor.MD}}}{kind}", "Existing child kind differs", 3)
        logical_path = parent_path + "." + kind + "." + name
        occupied = borrow._uuid_inventory(snapshot, external_name=editor.node_name(owner) if owner is config else None)
        identity = editor.allocate_uuid(
            editor.identity(config), kind, logical_path, "object", {} if existing else occupied
        )
        # Reuse the pure creation emitter, including owner-specific names/types.
        # Only the selected child enters the plan; its temporary owner is discarded.
        rendered_kind = {"ExternalReport": "Report", "ExternalDataProcessor": "DataProcessor"}.get(
            owner_kind, owner_kind
        )
        member = {key: value for key, value in attribute.items() if key not in {"after", "before"}}
        rendered_definition = {
            "type": rendered_kind,
            "name": editor.node_name(owner),
            "values" if collection == "enumValues" else collection: [member],
        }
        if section_name is not None:
            rendered_definition = {
                "type": rendered_kind,
                "name": editor.node_name(owner),
                "tabularSections": [{"name": section_name, "attributes": [member]}],
            }
        rendered = editor.metadata(
            create.render_object(rendered_definition, editor.identity(config), {}), rendered_kind
        )
        candidate = (
            rendered.find("m:ChildObjects/m:TabularSection/m:ChildObjects/m:Attribute", editor.NS)
            if section_name
            else (rendered.find(f"{{{editor.MD}}}ChildObjects/{{{editor.MD}}}{kind}"))
        )
        editor.require(candidate is not None, "Child generator produced no candidate", 4)
        # Keep inherited bindings used in QName text when detaching the child.
        candidate = etree.fromstring(etree.tostring(candidate))
        candidate.set("uuid", identity)
        if kind == "TabularSection":
            for generated in candidate.findall("m:InternalInfo/xr:GeneratedType", {**editor.NS, "xr": borrow.XR}):
                type_name = owner_kind + generated.get("category") + "." + editor.node_name(owner) + "." + name
                generated.set("name", type_name)
                for role in ("TypeId", "ValueId"):
                    generated.find(f"{{{borrow.XR}}}{role}").text = editor.allocate_uuid(
                        editor.identity(config),
                        kind,
                        logical_path,
                        type_name + ":" + role,
                        {} if existing else occupied,
                    )
            nested = candidate.find("m:ChildObjects", editor.NS)
            members = list(nested)
            nested[:] = []
            for child, requested in zip(members, attribute.get("attributes", []), strict=False):
                child.set(
                    "uuid",
                    editor.allocate_uuid(
                        editor.identity(config),
                        "Attribute",
                        logical_path + ".Attribute." + editor.node_name(child),
                        "object",
                        {} if existing else occupied,
                    ),
                )
                insert_child(nested, child, requested)
        if kind == "Attribute" and owner_kind in REGISTER_KINDS:
            # meta-edit omits these optional properties for register attributes.
            props = candidate.find(f"{{{editor.MD}}}Properties")
            for property_name in ("FillFromFillingValue", "FillValue"):
                prop_node = props.find(f"{{{editor.MD}}}{property_name}")
                if prop_node is not None:
                    props.remove(prop_node)
        if insert_child(container, candidate, attribute):
            # Make each addition visible to identity checks of the next addition.
            snapshot.stage(path, editor.serialize_like(owner.getparent(), original))

    def remove(collection, name, container, parent_path, reserved_names, section_name=None):
        kind = ADD_KINDS[collection]
        editor.require(
            editor.NAME.fullmatch(name)
            and name.casefold() not in {value.casefold() for value in reserved_names if value},
            "Cannot remove a reserved child",
        )
        rendered_kind = {"ExternalReport": "Report", "ExternalDataProcessor": "DataProcessor"}.get(
            owner_kind, owner_kind
        )
        definition = {
            "type": rendered_kind,
            "name": editor.node_name(owner),
            "values" if collection == "enumValues" else collection: [{"name": name}],
        }
        if section_name is not None:
            definition = {
                "type": rendered_kind,
                "name": editor.node_name(owner),
                "tabularSections": [{"name": section_name, "attributes": [{"name": name}]}],
            }
        rendered = editor.metadata(create.render_object(definition, editor.identity(config), {}), rendered_kind)
        matches = (
            [node for node in container if (editor.prop(node, "Name") or node.text or "").casefold() == name.casefold()]
            if container is not None
            else []
        )
        editor.require(
            len(matches) <= 1
            and all(node.tag == f"{{{editor.MD}}}{kind}" and editor.node_name(node) == name for node in matches),
            "Ambiguous removal target",
            3,
        )
        child = matches[0] if matches else None
        if child is not None:
            editor.require(
                not any(
                    editor.prop(node, "ObjectBelonging") == "Adopted"
                    or editor.prop(node, "ExtendedConfigurationObject")
                    for node in child.iter()
                ),
                "Cannot remove an adopted child",
                3,
            )
        documents, _ = read_dependency_documents(snapshot, owner, path, reviewed_dependencies=reviewed_dependencies)
        sample = child if child is not None else rendered
        generated_names = (
            {
                node.get("name"): node.get("name")
                for node in sample.iter(f"{{{borrow.XR}}}GeneratedType")
                if node.get("name", "").endswith("." + name)
            }
            if kind == "TabularSection"
            else {}
        )
        if child is not None:
            assert container is not None
            container.remove(child)
        check_or_rewrite_references(
            snapshot,
            documents,
            owner,
            path,
            original,
            False,
            name,
            parent_path + "." + kind + "." + name,
            None,
            generated_names,
            removed_ids={editor.identity(node) for node in child.iter() if node.get("uuid")}
            if child is not None
            else set(),
        )

    removed_registration_references = []
    excluded_registration_files = set()

    def registration(collection, name, removing=False):
        child_kind = "Form" if collection == "forms" else "Command"
        editor.require(
            editor.NAME.fullmatch(name) and name.casefold() not in {value.casefold() for value in reserved if value},
            "Invalid or reserved registration name",
            3,
        )
        matches = (
            [
                child
                for child in children
                if (editor.prop(child, "Name") or child.text or "").casefold() == name.casefold()
            ]
            if children is not None
            else []
        )
        editor.require(
            len(matches) <= 1
            and all(
                child.tag == f"{{{editor.MD}}}{child_kind}"
                and child.text == name
                and not child.attrib
                and not len(child)
                and not (child.tail or "").strip()
                for child in matches
            ),
            "Ambiguous child registration",
            3,
        )
        if not removing:
            if not matches:
                assert children is not None
                candidate = etree.Element(f"{{{editor.MD}}}{child_kind}")
                candidate.text = name
                following = next(
                    (
                        child
                        for child in children
                        if child_kind == "Form" and etree.QName(child).localname in {"Template", "Command"}
                    ),
                    None,
                )
                children.insert(children.index(following), candidate) if following is not None else children.append(
                    candidate
                )
            return
        folder = path.removesuffix(".xml") + "/" + child_kind + "s/" + name
        excluded = set()
        descriptor = snapshot.read("target", folder + ".xml", optional=True)
        removed_ids = set()
        if descriptor is not None:
            excluded.add(folder + ".xml")
            member = editor.metadata(descriptor, child_kind)
            editor.require(editor.node_name(member) == name, "Child descriptor name mismatch", 3)
            removed_ids.add(editor.identity(member))

        def inventory(directory):
            for filename, entry_kind in (snapshot.list_directory("target", directory, optional=True) or {}).items():
                file_path = directory + "/" + filename
                if entry_kind == "directory":
                    inventory(file_path)
                else:
                    snapshot.read("target", file_path)
                    excluded.add(file_path)

        inventory(folder)
        if matches:
            assert children is not None
            children.remove(matches[0])
        excluded_registration_files.update(excluded)
        removed_registration_references.append((child_kind, name, removed_ids))

    for collection, members in additions.items():
        for member in members:
            if collection in REGISTRATION_OWNERS:
                registration(collection, member["name"])
            else:
                add(collection, member, children, operation["target"], reserved)
    for collection, names in removals.items():
        for name in names:
            if collection in REGISTRATION_OWNERS:
                registration(collection, name, removing=True)
            else:
                remove(collection, name, children, operation["target"], reserved)

    def modify(child, values, parent_path, reserved_names):
        editor.require(bool(values), "Empty modification")
        editor.require(not ("name" in values and "Name" in values), "Duplicate property alias")
        if "name" in values or "Name" in values:
            rename_metadata(
                snapshot,
                owner,
                path,
                original,
                child,
                values.get("name", values.get("Name")),
                parent_path,
                reserved_names,
                config=config,
            )
        properties = {key: value for key, value in values.items() if key not in {"name", "Name"}}
        if properties:
            modify_properties(child, properties)

    for name, changes in modifications.get("tabularSections", {}).items():
        if children is None:
            raise editor.Rejected("Missing section ChildObjects", 4)
        matches = [
            child
            for child in children
            if child.tag == f"{{{editor.MD}}}TabularSection"
            and editor.prop(child, "Name").casefold() == name.casefold()
        ]
        editor.require(
            len(matches) == 1 and editor.node_name(matches[0]) == name, "Missing or ambiguous tabular section", 3
        )
        section = matches[0]
        nested_reserved = {"LineNumber", "НомерСтроки"}
        base_sections = (
            [
                child
                for child in base.findall("m:ChildObjects/m:TabularSection", editor.NS)
                if editor.prop(child, "Name").casefold() == name.casefold()
            ]
            if base is not None
            else []
        )
        if editor.prop(section, "ObjectBelonging") == "Adopted":
            editor.require(
                len(base_sections) == 1
                and editor.node_name(base_sections[0]) == name
                and editor.identity(base_sections[0]) == editor.prop(section, "ExtendedConfigurationObject").lower(),
                "Exact base section context required",
                3,
            )
            nested_reserved.update(
                editor.prop(child, "Name") for child in base_sections[0].findall("m:ChildObjects/*", editor.NS)
            )
        else:
            editor.require(not base_sections, "Native section conflicts with base section", 3)
        containers = section.findall("m:ChildObjects", editor.NS)
        editor.require(len(containers) == 1, "Missing or ambiguous section ChildObjects", 4)
        for member in changes.get("add", []):
            add(
                "attributes",
                member,
                containers[0],
                operation["target"] + ".TabularSection." + name,
                nested_reserved,
                name,
            )
        for member in changes.get("remove", []):
            remove(
                "attributes",
                member,
                containers[0],
                operation["target"] + ".TabularSection." + name,
                nested_reserved,
                name,
            )
        for attribute_name, values in changes.get("modify", {}).items():
            modify(
                borrow._member(section, "Attribute", attribute_name),
                values,
                operation["target"] + ".TabularSection." + name,
                nested_reserved,
            )
        properties = {key: value for key, value in changes.items() if key not in {"add", "modify", "remove"}}
        if properties:
            modify(section, properties, operation["target"], reserved)
    for change in definition.get("_complex", []):
        edit_reference_list(snapshot, owner, change["property"], change["action"], change["values"], base)
    for collection, changes in modifications.items():
        if collection == "tabularSections":
            continue
        if collection == "properties":
            list_keys = {"Owners", "RegisterRecords", "BasedOn", "InputByString"}
            for key in (key for key in changes if key in list_keys):
                editor.require(isinstance(changes[key], list), "Reference list requires an array")
                edit_reference_list(snapshot, owner, key, "set", changes[key], base)
            properties = {key: value for key, value in changes.items() if key != "Name" and key not in list_keys}
            if properties:
                modify_properties(owner, properties)
        else:
            for name, values in changes.items():
                modify(borrow._member(owner, ADD_KINDS[collection], name), values, operation["target"], reserved)
    if exchange_plan_content:
        replacement = exchange_plan_content["replaceMetadata"]
        replace_exchange_plan_content_reference(
            snapshot,
            editor.node_name(owner),
            replacement["from"],
            replacement["to"],
        )
    if removed_registration_references:
        documents, _ = read_dependency_documents(
            snapshot,
            owner,
            path,
            excluded_files=excluded_registration_files,
            reviewed_dependencies=reviewed_dependencies,
        )
        for child_kind, name, removed_ids in removed_registration_references:
            check_or_rewrite_references(
                snapshot,
                documents,
                owner,
                path,
                original,
                False,
                name,
                operation["target"] + "." + child_kind + "." + name,
                None,
                {},
                removed_ids=removed_ids,
            )
    if editor.signature(owner) != before_signature:
        snapshot.stage(path, editor.serialize_like(owner.getparent(), original))
    if "Name" in modifications.get("properties", {}):
        rename_metadata(
            snapshot,
            owner,
            path,
            original,
            owner,
            modifications["properties"]["Name"],
            operation["target"],
            set(),
            config=config,
        )
